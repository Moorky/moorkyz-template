import fs from "node:fs";
import path from "node:path";

// Shared markup and generated index for the one search component used by every design page.
const escape = (value) => String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
const plain = (html) => html.replace(/<[^>]*>/g, "").replaceAll("&quot;", '"').replaceAll("&gt;", ">").replaceAll("&lt;", "<").replaceAll("&amp;", "&").trim();
export const searchScripts = ["assets/predictive-search.js", "assets/search-index.js", "assets/site-search.js"];

export function searchHead(root) {
  return `<link rel="stylesheet" href="${root}assets/search.css">${searchScripts.map((script) => `<script src="${root}${script}" defer></script>`).join("")}`;
}

export function searchBox({ root, kind, design = "" }) {
  if (!["showcase", "landing", "readme"].includes(kind)) throw new Error(`Unknown search page kind '${kind}'.`);
  return `<form class="site-search" role="search" action="${root}index.html#collection" data-site-search data-search-root="${root}" data-search-kind="${kind}"${design ? ` data-search-design="${escape(design)}"` : ""}><label class="site-search-label" for="site-search">Search the collection</label><span class="site-search-icon" aria-hidden="true"></span><input id="site-search" name="q" type="search" placeholder="Search templates, styles, pages" autocomplete="off" spellcheck="false" enterkeyhint="search"></form>`;
}

function readDictionary(directory) {
  const filename = path.join(directory, "search-dictionary.json");
  const dictionary = JSON.parse(fs.readFileSync(filename, "utf8"));
  if (!Array.isArray(dictionary.entries)) throw new Error("search-dictionary.json: 'entries' must be an array.");
  const seen = new Set();
  return dictionary.entries.map((entry, index) => {
    const where = `search-dictionary.json entry ${index + 1}`;
    const unknown = Object.keys(entry).filter((key) => !["value", "kind", "weight", "aliases", "href"].includes(key));
    if (unknown.length) throw new Error(`${where}: unknown field(s) ${unknown.join(", ")}.`);
    if (typeof entry.value !== "string" || !entry.value.trim()) throw new Error(`${where}: 'value' is required.`);
    if (typeof entry.kind !== "string" || !/^[A-Z][A-Za-z ]{1,20}$/.test(entry.kind)) throw new Error(`${where}: 'kind' must be a short capitalized label.`);
    if (entry.weight !== undefined && !Number.isFinite(entry.weight)) throw new Error(`${where}: 'weight' must be a number.`);
    if (entry.aliases !== undefined && (!Array.isArray(entry.aliases) || entry.aliases.some((alias) => typeof alias !== "string" || !alias.trim()))) throw new Error(`${where}: 'aliases' must be non-empty strings.`);
    const key = entry.value.trim().toLowerCase();
    if (seen.has(key)) throw new Error(`${where}: duplicate value '${entry.value}'.`);
    seen.add(key);
    if (entry.href !== undefined) {
      if (typeof entry.href !== "string" || /^(?:[a-z][a-z0-9+.-]*:|\/|\\)/i.test(entry.href)) throw new Error(`${where}: 'href' must be a relative local path.`);
      const local = decodeURIComponent(entry.href.split(/[?#]/)[0]);
      if (!local || !fs.existsSync(path.resolve(directory, local))) throw new Error(`${where}: '${entry.href}' does not exist.`);
    }
    return { value: entry.value.trim(), kind: entry.kind, weight: entry.weight ?? 0, aliases: entry.aliases ?? [], ...(entry.href ? { href: entry.href } : {}) };
  });
}

export function searchIndex({ directory, designs, documentationThemes, chapters }) {
  const chapterHome = designs.find((d) => documentationThemes.includes(d.art));
  const data = {
    chapterHome: `${chapterHome.id}/README.html`,
    designs: designs.map((d) => ({ id: d.id, name: d.name, note: d.note, category: d.category, tone: d.tone, compact: documentationThemes.includes(d.art) })),
    chapters: chapters.map(({ id, title }) => ({ id, title: plain(title) })),
    entries: readDictionary(directory),
  };
  return `"use strict";
// Generated by designs/build.mjs from catalog.mjs, README.md and search-dictionary.json.
// Do not edit; regenerate with node designs/build.mjs.
globalThis.MoorkyzSearchIndex = ${JSON.stringify(data, null, 1)};
`;
}
